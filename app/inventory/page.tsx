// ─── Types ────────────────────────────────────────────────────────────────────
type InventoryItem = {
  $id: string;
  $createdAt?: string;
  name: string;
  sku?: string;
  category: string;
  unit?: string;
  quantity: number;
  minQuantity?: number;
  unitPrice?: number;
  totalValue?: number;
  supplier?: string;
  location?: string;
  description?: string;
  imageUrl?: string;
  status?: "in_stock" | "low_stock" | "out_of_stock" | "discontinued";
  lastRestockedAt?: string;
};

type StockMovement = {
  type: "in" | "out" | "adjustment";
  quantity: number;
  reason: string;
  date: string;
  by?: string;
};

