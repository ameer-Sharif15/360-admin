import type jsPDF from 'jspdf';

export const COMPANY_INFO = {
  name: '360 DEGREE GLOBAL ESTATE LTD.',
  subline: 'Real Estate, Hospitality, Minimart, Facilities & Services',
  address: 'NSUK 2nd Gate, Behind Princess Sarah Hotel, Keffi, Nasarawa State',
  contact: 'Tel: 08038923692, 08136661966  |  Email: info@360degreeglobal.org',
  website: 'www.360degreeglobal.org',
  itDeptSignature: () =>
    `Verified & Generated by IT Department · 360 Degree Global Estate Ltd. · ${new Date().toLocaleString('en-NG')}`,
};

let cachedLogoDataUrl: string | null = null;

export async function getLogoDataUrl(): Promise<string | null> {
  if (cachedLogoDataUrl) return cachedLogoDataUrl;
  if (typeof window === 'undefined') return null;
  try {
    const res = await fetch('/logo.png');
    if (!res.ok) return null;
    const blob = await res.blob();
    return new Promise((resolve) => {
      const reader = new FileReader();
      reader.onloadend = () => {
        cachedLogoDataUrl = reader.result as string;
        resolve(cachedLogoDataUrl);
      };
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch (_) {
    return null;
  }
}

export interface LetterheadOptions {
  title: string;
  subtitle?: string;
  docRef?: string;
  badge?: string;
}

/**
 * Draws the 360 Degree Letterhead at the top of a jsPDF document.
 * Returns the Y coordinate where following content should start.
 */
export async function drawLetterhead(
  doc: jsPDF,
  options: LetterheadOptions
): Promise<number> {
  const pageWidth = doc.internal.pageSize.getWidth();
  const isLandscape = pageWidth > 220;

  // Top color accents
  doc.setFillColor(26, 54, 93); // Navy #1A365D
  doc.rect(0, 0, pageWidth, 5, 'F');
  doc.setFillColor(255, 127, 80); // Coral #FF7F50
  doc.rect(0, 5, pageWidth, 2, 'F');

  const logoData = await getLogoDataUrl();
  const leftMargin = 14;
  const logoSize = 20;

  if (logoData) {
    try {
      doc.addImage(logoData, 'PNG', leftMargin, 10, logoSize, logoSize);
    } catch (_) {
      drawFallbackLogo(doc, leftMargin, 10, logoSize);
    }
  } else {
    drawFallbackLogo(doc, leftMargin, 10, logoSize);
  }

  // Company details next to logo
  const textX = leftMargin + logoSize + 4;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.setTextColor(26, 54, 93);
  doc.text(COMPANY_INFO.name, textX, 16);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.text(COMPANY_INFO.subline, textX, 21);

  doc.setFontSize(7.5);
  doc.setTextColor(71, 85, 105);
  doc.text(COMPANY_INFO.address, textX, 26);
  doc.text(COMPANY_INFO.contact, textX, 30);

  // Right-side badge / metadata
  const rightX = pageWidth - 14;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(255, 127, 80);
  doc.text('OFFICIAL DOCUMENT', rightX, 15, { align: 'right' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(100, 116, 139);
  doc.text(`Date: ${new Date().toLocaleDateString('en-GB')}`, rightX, 19.5, { align: 'right' });
  if (options.docRef) {
    doc.text(`Ref: ${options.docRef}`, rightX, 23.5, { align: 'right' });
  }

  // IT Verified & Audited Official Badge Pill (Responsively sized & positioned)
  const badgeWidth = 44;
  const badgeHeight = 5.8;
  const badgeX = rightX - badgeWidth;
  const badgeY = options.docRef ? 26.5 : 24.5;

  // Emerald badge background & border
  doc.setFillColor(236, 253, 245); // Emerald 50
  doc.roundedRect(badgeX, badgeY, badgeWidth, badgeHeight, 1.8, 1.8, 'F');
  doc.setDrawColor(16, 185, 129); // Emerald 500
  doc.setLineWidth(0.3);
  doc.roundedRect(badgeX, badgeY, badgeWidth, badgeHeight, 1.8, 1.8, 'S');

  // Badge text
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(6.8);
  doc.setTextColor(6, 95, 70); // Emerald 800
  doc.text('✔ IT VERIFIED & SECURE', badgeX + badgeWidth / 2, badgeY + 4.1, { align: 'center' });

  // Divider Line
  doc.setDrawColor(255, 127, 80);
  doc.setLineWidth(0.8);
  doc.line(leftMargin, 37, pageWidth - 14, 37);

  // Document Title Banner
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(leftMargin, 40, pageWidth - 28, 14, 2, 2, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.3);
  doc.roundedRect(leftMargin, 40, pageWidth - 28, 14, 2, 2, 'S');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(26, 54, 93);
  doc.text(options.title.toUpperCase(), leftMargin + 4, 48);

  if (options.subtitle) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(options.subtitle, leftMargin + 4, 52);
  }

  if (options.badge) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(255, 127, 80);
    doc.text(options.badge, rightX - 4, 49, { align: 'right' });
  }

  return 58; // Next content Y position
}

function drawFallbackLogo(doc: jsPDF, x: number, y: number, size: number) {
  doc.setFillColor(26, 54, 93);
  doc.roundedRect(x, y, size, size, 3, 3, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(255, 127, 80);
  doc.text('360°', x + size / 2, y + size / 2 + 3, { align: 'center' });
}

/**
 * Iterates through all pages of the document and stamps the IT Department signature
 * and page numbers at the bottom.
 */
export function stampDocumentFooter(doc: jsPDF, customNote?: string) {
  const totalPages = doc.getNumberOfPages();
  const itSign = COMPANY_INFO.itDeptSignature();

  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();

    // Divider line
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.4);
    doc.line(14, pageHeight - 12, pageWidth - 14, pageHeight - 12);

    // Left & Center: IT department sign
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.5);
    doc.setTextColor(100, 116, 139);
    doc.text(itSign + (customNote ? ` · ${customNote}` : ''), 14, pageHeight - 7);

    // Right: Page number
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(71, 85, 105);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - 14, pageHeight - 7, { align: 'right' });
  }
}
